export const getSubjectChapters = (subject, classNum) => {
  const key = `${subject.toLowerCase()}_${classNum}`;
  return RBSE_CURRICULUM[key]?.chapters || [];
};

export const getAllSubjects = (classNum) => {
  const subjects = Object.values(RBSE_CURRICULUM)
    .filter(curr => !classNum || curr.class === classNum)
    .map(curr => curr.subject);
  return [...new Set(subjects)];
};
